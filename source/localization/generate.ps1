$ErrorActionPreference = 'Stop'
$catalog = Get-Content -LiteralPath (Join-Path $PSScriptRoot 'strings.json') -Raw -Encoding UTF8 | ConvertFrom-Json

function ConvertTo-WideLiteral([string]$Value) {
    'L' + (ConvertTo-Json -InputObject $Value -Compress)
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('#pragma once')
$lines.Add('// Generated by localization/generate.ps1; edit localization/strings.json.')
$lines.Add('#include <cstddef>')
$lines.Add('namespace Localization {')
$lines.Add('enum TextId : std::size_t {')
$lines.Add('    ' + (($catalog.entries | ForEach-Object { $_.id }) -join ', '))
$lines.Add('};')
$lines.Add('struct Translation { const wchar_t* key; const wchar_t* chinese; const wchar_t* english; };')
$lines.Add('inline constexpr Translation Strings[]={')
foreach ($entry in $catalog.entries) {
    if ([string]::IsNullOrEmpty($entry.'zh-CN') -or [string]::IsNullOrEmpty($entry.'en-US')) {
        throw "Translation required: $($entry.id)"
    }
    $values = @($entry.id, $entry.'zh-CN', $entry.'en-US') | ForEach-Object { ConvertTo-WideLiteral $_ }
    $lines.Add('    {' + ($values -join ',') + '},')
}
$lines.Add('};')
$lines.Add('inline constexpr TextId XamlStrings[]={')
$lines.Add('    ' + ($catalog.xamlStrings -join ', '))
$lines.Add('};')
$lines.Add('}')
$output = Join-Path (Split-Path -Parent $PSScriptRoot) 'localization_strings.h'
$generated = ($lines -join "`r`n") + "`r`n"
if (!(Test-Path -LiteralPath $output) -or [System.IO.File]::ReadAllText($output) -cne $generated) {
    [System.IO.File]::WriteAllText($output, $generated, [System.Text.UTF8Encoding]::new($false))
}
